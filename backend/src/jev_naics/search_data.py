"""NAICS search data (JEV-50): every 2022 industry's full official text, as package data.

Generated by build_search.py from the Census files; the search database is loaded from it, so a
Docker image needs no spreadsheets. Per industry:
- description   the official description, without its examples and cross-reference sections
- examples      the "Illustrative Examples" list
- index_entries every Census index entry for the code (20,373 in all)
- excludes      (code it goes to, activity) for each cross-reference under this industry or its
                5-digit parent: activities the Census classifies elsewhere
- sent_here     activities other industries' cross-references send to this industry
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

SEARCH_DATA_PATH = Path(__file__).resolve().parent / "data" / "naics_2022_search.json"


@dataclass(frozen=True)
class Industry:
    code: str
    title: str
    description: str
    examples: tuple[str, ...]
    index_entries: tuple[str, ...]
    excludes: tuple[tuple[str, str], ...]
    sent_here: tuple[str, ...]


@dataclass(frozen=True)
class SearchData:
    source: str
    version: str  # a hash of the industries, so the database reloads only when they change
    industries: dict[str, Industry]


@lru_cache(maxsize=1)
def load_search_data() -> SearchData:
    raw = json.loads(SEARCH_DATA_PATH.read_text(encoding="utf-8"))
    industries = {
        code: Industry(code=code, title=i["title"], description=i["description"],
                       examples=tuple(i["examples"]), index_entries=tuple(i["index_entries"]),
                       excludes=tuple((c, a) for c, a in i["excludes"]), sent_here=tuple(i["sent_here"]))
        for code, i in raw["industries"].items()
    }
    return SearchData(source=raw["source"], version=raw["version"], industries=industries)
